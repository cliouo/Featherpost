"""Bundle the design prototype into one HTML file that opens without a server."""

from pathlib import Path

root = Path(__file__).resolve().parent
source = root / "prototype"
html = (source / "index.html").read_text()
css = (source / "style.css").read_text()
style_link = '<link rel="stylesheet" href="style.css">'
assert html.count(style_link) == 1, "Prototype stylesheet entry changed"
html = html.replace(style_link, f"<style>\n{css}\n</style>")
for script_name in ("app.js", "extensions.js"):
    script_link = f'<script src="{script_name}"></script>'
    assert html.count(script_link) == 1, f"Prototype entry changed: {script_name}"
    js = (source / script_name).read_text().replace("</script", "<\\/script")
    html = html.replace(script_link, f"<script>\n{js}\n</script>")
html = html.replace('href="../README.md"', 'href="README.md"')
html = html.replace("<!doctype html>", "<!doctype html>\n<!-- Generated by build-preview.py; edit prototype/ sources. -->", 1)
output = root / "Maild-UI-Preview.html"
output.write_text(html)
print(output)
